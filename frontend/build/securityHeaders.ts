import { loadEnv, type Plugin } from 'vite'

// Response headers for the deployed site, written to dist/_headers at build
// time (Cloudflare Workers static assets read that file). Generated rather than
// kept in public/ because the Content-Security-Policy has to name the exact
// Supabase project and Sentry host of the build, which differ per environment.

export interface HeaderEnv {
  /** https://<project-ref>.supabase.co; empty in CI builds, which are never deployed. */
  supabaseUrl: string
  /** Empty = error reporting is off for this build (lib/monitoring.ts). */
  sentryDsn: string
  appEnv: string
}

const SUPABASE_URL = /^https:\/\/[a-z0-9-]+\.supabase\.co$/
// Same shape lib/monitoring.ts accepts: https://<key>@<host>/<project-id>
const SENTRY_DSN = /^https:\/\/([^@\s]+)@([^/\s]+)\/(\d+)$/

// Razorpay Checkout, as its script (checkout.razorpay.com/v1/checkout.js)
// actually uses it from our page: the payment window is a frame on api, the
// script also calls api and can post a redirect form to it, it loads a second
// script (risk detection) and payment app icons from cdn, and sends its own
// analytics to the lumberjack hosts. Found by loading Checkout under this
// policy; the cdn script was blocked until listed. Anything inside the payment
// frame is governed by Razorpay's own policy, not this one.
const RAZORPAY = {
  script: 'https://checkout.razorpay.com',
  api: 'https://api.razorpay.com',
  cdn: 'https://cdn.razorpay.com',
  analytics: [
    'https://lumberjack.razorpay.com',
    'https://lumberjack-cx.razorpay.com',
    'https://lumberjack-metrics.razorpay.com',
  ],
}

// The Console's venue map (PinMap) and address search (addressSearch).
const OSM_TILES = 'https://tile.openstreetmap.org'
const NOMINATIM = 'https://nominatim.openstreetmap.org'

export function contentSecurityPolicy(env: HeaderEnv): string {
  const supabase: string[] = []
  if (env.supabaseUrl !== '') {
    if (!SUPABASE_URL.test(env.supabaseUrl)) {
      throw new Error(
        `VITE_SUPABASE_URL must look like https://<project-ref>.supabase.co (got "${env.supabaseUrl}")`,
      )
    }
    // https for RPCs and Edge Functions, wss for Realtime.
    supabase.push(env.supabaseUrl, env.supabaseUrl.replace('https://', 'wss://'))
  }

  const sentry: string[] = []
  const report: string[] = []
  if (env.sentryDsn !== '') {
    const match = SENTRY_DSN.exec(env.sentryDsn)
    if (!match) {
      throw new Error('VITE_SENTRY_DSN must look like https://<key>@<host>/<project-id>')
    }
    const [, key, host, project] = match
    sentry.push(`https://${host}`)
    // Violations reach Sentry, so a blocked origin is seen instead of silently
    // breaking a screen. The key is the DSN's public key, already in the bundle.
    const query = new URLSearchParams({ sentry_key: key, sentry_environment: env.appEnv })
    report.push(`report-uri https://${host}/api/${project}/security/?${query.toString()}`)
  }

  return [
    "default-src 'self'",
    `script-src 'self' ${RAZORPAY.script} ${RAZORPAY.cdn}`,
    // 'unsafe-inline' for styles only: Razorpay Checkout writes its overlay as
    // markup with style attributes. Styles cannot run code; scripts stay strict.
    "style-src 'self' 'unsafe-inline'",
    // data: for small images and fonts Vite inlines into the CSS (Leaflet's).
    `img-src 'self' data: blob: ${OSM_TILES} ${RAZORPAY.cdn}`,
    "font-src 'self' data:",
    [
      'connect-src',
      "'self'",
      ...supabase,
      NOMINATIM,
      RAZORPAY.api,
      ...RAZORPAY.analytics,
      ...sentry,
    ].join(' '),
    `frame-src ${RAZORPAY.api}`,
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    `form-action 'self' ${RAZORPAY.api}`,
    "frame-ancestors 'none'",
    ...report,
  ].join('; ')
}

export function headersFile(env: HeaderEnv): string {
  return `# Generated by build/securityHeaders.ts. Edit that file, not this one.

/*
  Content-Security-Policy: ${contentSecurityPolicy(env)}
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Permissions-Policy: geolocation=(self), camera=(), microphone=(), usb=()

# The service worker and manifest must never be served stale from a cache, or an
# installed app could keep running an old version long after a fix is deployed.
/sw.js
  Cache-Control: no-cache
/manifest.webmanifest
  Cache-Control: no-cache

# Hashed build files never change under the same name.
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`
}

/** Writes dist/_headers for the build's mode (.env files, same as the app). */
export function securityHeaders(): Plugin {
  let env: HeaderEnv = { supabaseUrl: '', sentryDsn: '', appEnv: '' }
  return {
    name: 'introchat-security-headers',
    apply: 'build',
    configResolved(config) {
      const raw = loadEnv(config.mode, config.envDir, 'VITE_')
      env = {
        supabaseUrl: raw.VITE_SUPABASE_URL?.trim() ?? '',
        sentryDsn: raw.VITE_SENTRY_DSN?.trim() ?? '',
        appEnv: raw.VITE_APP_ENV?.trim() || 'local',
      }
      if (env.supabaseUrl === '') {
        config.logger.warn(
          'VITE_SUPABASE_URL is not set: this build cannot reach Supabase and its CSP does not list it. Fine for CI, never for a deploy.',
        )
      }
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: '_headers', source: headersFile(env) })
    },
  }
}
